import 'dart:io';

/// Usage: dart run dlm_tools:export_screenshots
///
/// Copies the golden images of the app screens to docs/images, so the guide's
/// screenshots are the ones the tests check and cannot drift from the app.
/// Goldens are only valid when produced on the pinned CI image; the images in
/// the repository are those, so this is a plain copy.
void main() {
  final source = Directory('apps/dlm_app/test/golden/goldens');
  if (!source.existsSync()) {
    stderr.writeln('run from the repository root');
    exit(2);
  }
  final target = Directory('docs/images');
  if (target.existsSync()) target.deleteSync(recursive: true);
  target.createSync(recursive: true);

  final skins = [
    for (final e in source.listSync())
      if (e is Directory) e.uri.pathSegments.where((s) => s.isNotEmpty).last,
  ]..sort();
  const screens = {
    'downloads': 'The downloads list',
    'add_dialog': 'The add dialog',
    'settings': 'The settings window',
  };
  final readme = StringBuffer()
    ..writeln('# Screenshots')
    ..writeln()
    ..writeln(
      'Generated by `dart run dlm_tools:export_screenshots` from the golden '
      'images of `apps/dlm_app/test/golden`; do not edit them by hand. One '
      'skin per operating system: `macos`, `fluent` (Windows), `adwaita` '
      '(GNOME) and `breeze` (KDE).',
    );
  for (final skin in skins) {
    Directory('docs/images/$skin').createSync();
    readme
      ..writeln()
      ..writeln('## $skin');
    for (final entry in screens.entries) {
      readme
        ..writeln()
        ..writeln('**${entry.value}**, light and dark:')
        ..writeln();
      for (final theme in const ['light', 'dark']) {
        final name = '${entry.key}_$theme.png';
        final file = File('${source.path}/$skin/$name');
        if (!file.existsSync()) {
          stderr.writeln('missing golden: ${file.path}');
          exit(1);
        }
        file.copySync('docs/images/$skin/$name');
        readme.writeln('![${entry.value}, $skin, $theme]($skin/$name)');
      }
    }
  }
  File('docs/images/README.md').writeAsStringSync(readme.toString());
  stdout.writeln('${skins.length} skins exported to docs/images');
}
